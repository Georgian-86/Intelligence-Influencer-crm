// Regenerates the college seed block inside supabase/migrations/0005_v2_onboarding.sql
// from lib/colleges-data.ts.  Usage: node scripts/seed-colleges.mjs   (Node >= 22.18, type stripping)
//   --print   only print the SQL instead of rewriting the migration.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COLLEGE_SEED } from "../lib/colleges-data.ts";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = COLLEGE_SEED.map((c) => `  (${q(c.name)}, ${q(c.city)}, ${q(c.state)}, ${q(c.type)})`);
const sql = [
  "-- BEGIN COLLEGE SEED (generated by scripts/seed-colleges.mjs; edit lib/colleges-data.ts instead)",
  "insert into public.colleges (name, city, state, type) values",
  rows.join(",\n"),
  "on conflict do nothing;",
  "-- END COLLEGE SEED",
].join("\n");

if (process.argv.includes("--print")) {
  console.log(sql);
} else {
  const file = fileURLToPath(new URL("../supabase/migrations/0005_v2_onboarding.sql", import.meta.url));
  const src = readFileSync(file, "utf8");
  const re = /-- BEGIN COLLEGE SEED[\s\S]*?-- END COLLEGE SEED/;
  if (!re.test(src)) throw new Error("Seed markers not found in migration");
  writeFileSync(file, src.replace(re, () => sql));
  console.log(`Wrote ${COLLEGE_SEED.length} colleges into ${file}`);
}
